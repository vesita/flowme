def build() -> dict:
    cases: list[dict] = []

    def add(sid: str, text: str, cue: str, label: str, kind: str) -> None:
        if text.count(cue) != 1:
            raise SystemExit(f"{sid}: cue '{cue}' 在文本里出现 {text.count(cue)} 次：{text}")
        cases.append({
            "id": sid, "set": kind, "text": text, "cue": cue,
            "cue_start": text.index(cue), "cue_end": text.index(cue) + len(cue) - 1,
            "label": label, "sanity": text in SANITY,
        })

    for i, (t, c) in enumerate(NEG_SAD, 1):
        add(f"neg_sad_{i:02d}", t, c, "悲伤", "negation")
    for i, (t, c) in enumerate(NEG_ANGRY, 1):
        add(f"neg_angry_{i:02d}", t, c, "愤怒", "negation")
    for i, (t, c, y) in enumerate(CONTROL_PLAIN, 1):
        add(f"ctrl_plain_{i:02d}", t, c, y, "control")
    for i, (t, c, y) in enumerate(CONTROL_NEG_OTHER, 1):
        add(f"ctrl_neg_{i:02d}", t, c, y, "control")
    for i, (t, c) in enumerate(STRESS_POSITIVE, 1):
        add(f"stress_{i:02d}", t, c, "积极", "stress")

    n_sanity = sum(1 for c in cases if c["sanity"])
    if n_sanity < 10:
        raise SystemExit(f"已知答案对照只有 {n_sanity} 条，要求 ≥10")
    neg = [c for c in cases if c["set"] == "negation"]
    ctrl = [c for c in cases if c["set"] == "control"]
    if len(neg) < 60:
        raise SystemExit(f"否定评测集只有 {len(neg)} 条，要求 ≥60")
    if len([c for c in ctrl if c["set"] == "control" and c["id"].startswith("ctrl_plain")]) < 40:
        raise SystemExit("非否定对照句不足 40 条")
    return {"cases": cases, "counts": {
        "negation": len(neg), "control": len(ctrl),
        "control_plain": len([c for c in ctrl if c["id"].startswith("ctrl_plain")]),
        "stress": len([c for c in cases if c["set"] == "stress"]),
        "sanity": n_sanity,
    }}


if __name__ == "__main__":
    data = build()
    out = HERE / "dataset.json"
    out.write_text(json.dumps(data, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"{out}  {data['counts']}")
